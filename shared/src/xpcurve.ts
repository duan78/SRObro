/** XP cumulée pour atteindre le niveau donné (0 si niveau 1). */
export function cumulativeXpForLevel(level: number): number {
  if (level <= 1) return 0;
  const i = Math.min(level, CUMULATIVE_XP.length - 1);
  return CUMULATIVE_XP[i];
}

/** XP (à gagner depuis le niveau courant) pour monter au niveau suivant. */
export function xpForNextLevel(level: number): number {
  const next = cumulativeXpForLevel(level + 1);
  const cur = cumulativeXpForLevel(level);
  return next - cur;
}

export const MAX_LEVEL = CUMULATIVE_XP.length - 1;
